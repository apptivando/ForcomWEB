/**
 * Iconos del panel, en un solo lugar.
 *
 * Existe para que no se vuelvan a pegar paths de SVG sueltos por los
 * componentes —que es como los iconos terminan con tamaños y grosores
 * distintos según quién los copió— y para que "el icono de WhatsApp" sea
 * siempre el mismo dibujo.
 *
 * Convención del panel: trazo de 1,8 y 16 px por defecto. A 16 px con trazo
 * fino sobre fondo oscuro los iconos se pierden, que es justo el hallazgo D3
 * de la auditoría.
 */

type IconProps = {
  className?: string;
  /** Grosor del trazo. No aplica a los iconos de marca, que son rellenos. */
  strokeWidth?: number;
};

function Outline({
  className = "w-4 h-4",
  strokeWidth = 1.8,
  children,
}: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      className={className}
      fill="none"
      viewBox="0 0 24 24"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

